import {test,expect} from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
test("signup, login, approval, revocation and admin password recovery",async({page,request})=>{
  test.setTimeout(90000);
  const email=`browser-${test.info().project.name}-${Date.now()}@example.test`,password="browser-test-password";
  await page.goto('/#/signup');
  await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill(password);await page.getByLabel('Confirm password',{exact:true}).fill(password);
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByText('Account created. Log in to see your approval status.',{exact:false})).toBeVisible();
  await page.getByRole('link',{name:'Already registered? Log in',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill(password);await page.getByRole('button',{name:'Log in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your account',exact:true})).toBeVisible();
  await expect(page.getByText('Live access is pending or revoked.',{exact:false})).toBeVisible();
  expect((await page.request.get('/api/tickers?mode=live')).status()).toBe(403);
  const auth='Basic '+Buffer.from('qa-owner@example.test:local-browser-only').toString('base64');
  const users=await(await request.get('http://127.0.0.1:18092/api/admin/users?q='+email,{headers:{authorization:auth}})).json();
  const id=users.users[0].id;
  await request.post('http://127.0.0.1:18092/api/admin/users/'+id,{headers:{authorization:auth},data:{action:'approve'}});
  await page.reload();await expect(page.getByText('Live access approved.',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Renew login for 30 days',exact:true}).click();await expect(page.getByText('Login renewed for 30 days.',{exact:true})).toBeVisible();
  await page.screenshot({path:test.info().outputPath('account-approved.png'),fullPage:true});
  await page.getByRole('button',{name:'Live',exact:true}).click();
  await page.getByRole('link',{name:'Return to dashboard',exact:true}).click();
  await expect(page.getByText('Frozen evidence from this analysis',{exact:false})).toBeVisible();
  const live=await page.request.get('/api/tickers?mode=live');expect(live.status()).toBe(200);
  await request.post('http://127.0.0.1:18092/api/admin/users/'+id,{headers:{authorization:auth},data:{action:'revoke'}});
  expect((await page.request.get('/api/tickers?mode=live')).status()).toBe(401);
  await page.goto('/#/login');await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill(password);await page.getByRole('button',{name:'Log in',exact:true}).click();
  await expect(page.getByText('Live access is pending or revoked.',{exact:false})).toBeVisible();
  await request.post('http://127.0.0.1:18092/api/admin/users/'+id,{headers:{authorization:auth},data:{action:'resetPassword',password:'replacement-browser-password'}});
  await page.reload();await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill('replacement-browser-password');await page.getByRole('button',{name:'Log in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your account',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Log out',exact:true}).click();await expect(page.getByRole('heading',{name:'Welcome back',exact:true})).toBeVisible();
  expect((await page.context().cookies()).some(c=>c.name==='vf_account')).toBe(false);
});
test("anonymous Live sends users to login instead of calling the Live API",async({page})=>{
  await page.goto('/#/');await expect(page.getByRole('button',{name:'Save research note',exact:true})).toBeVisible();
  const calls:string[]=[];page.on('request',r=>{if(r.url().endsWith('/api/analyze')&&r.postDataJSON()?.mode==='live')calls.push(r.url());});
  await page.getByRole('button',{name:'Live',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Welcome back',exact:true})).toBeVisible();expect(calls).toEqual([]);
  await page.screenshot({path:test.info().outputPath('login-screen.png'),fullPage:true});
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
});
